# 2) Fixed-parameter rolling-origin ARIMA with delayed target observability
# -----------------------------------------------------------------------------
def _rolling_arima_one(h: int) -> Tuple[np.ndarray, Tuple[int, int, int]]:
    from pmdarima import auto_arima

    d = DATA / f"h{h}"
    y_tr = np.load(_need(d / "y_train.npy"), allow_pickle=False).astype(float)
    y_va = np.load(_need(d / "y_val.npy"), allow_pickle=False).astype(float)
    y_te = np.load(_need(d / "y_test.npy"), allow_pickle=False).astype(float)
    o_te = pd.to_datetime(np.load(_need(d / "origin_dates_test.npy"), allow_pickle=False))
    e_va = pd.to_datetime(np.load(_need(d / "target_end_dates_val.npy"), allow_pickle=False))
    e_te = pd.to_datetime(np.load(_need(d / "target_end_dates_test.npy"), allow_pickle=False))

    auto = auto_arima(y_tr, seasonal=False, trace=False, suppress_warnings=True,
                      error_action="ignore", stepwise=True)
    order = tuple(int(x) for x in auto.order)
    state = auto.arima_res_  # statsmodels SARIMAXResultsWrapper with fixed fitted params

    obs = np.concatenate([y_va, y_te])
    end_dates = np.concatenate([e_va.values, e_te.values]).astype("datetime64[ns]")
    n_val = len(y_va)
    appended = 0
    preds = np.empty(len(y_te), dtype=float)

    # At origin i, append every target whose future window has already ended.
    # Then forecast from the latest observed target-index to the current target-index.
    for i, origin in enumerate(o_te):
        origin64 = np.datetime64(origin.to_datetime64())
        eligible = int(np.searchsorted(end_dates, origin64, side="right"))
        if eligible > appended:
            state = state.append(obs[appended:eligible], refit=False)
            appended = eligible
        current_global = len(y_tr) + n_val + i
        last_observed_global = len(y_tr) + appended - 1
        steps = max(1, current_global - last_observed_global)
        fc = np.asarray(state.forecast(steps=steps), dtype=float)
        preds[i] = fc[-1]
    return preds.astype(np.float32), order


def rolling_arima() -> Path:
    rows = []
    out_dir = RESULTS / "rolling_arima"
    out_dir.mkdir(parents=True, exist_ok=True)
    for h in HORIZONS:
        pred, order = _rolling_arima_one(h)
        z_ref = _load_raw("AdaFracTCN", h)
        metrics = _score_saved(z_ref, pred)
        np.savez_compressed(out_dir / f"h{h}__arima_rolling.npz",
                            predictions_std=pred[None, :],
                            y_test_std=z_ref["y_test_std"],
                            origin_dates=z_ref["origin_dates"],
                            target_mean=z_ref["target_mean"], target_std=z_ref["target_std"],
                            positivity_floor=z_ref["positivity_floor"],
                            order=np.asarray(order, dtype=np.int64))
        # DM against the same AdaFracTCN ensemble used elsewhere.
        scaling = (float(z_ref["target_mean"]), float(z_ref["target_std"]))
        floor = float(z_ref["positivity_floor"])
        y = inverse_target(np.asarray(z_ref["y_test_std"], float), scaling)
        ada = inverse_target(np.asarray(z_ref["predictions_std"], float).mean(axis=0), scaling)
        ar = inverse_target(pred, scaling)
        ada = apply_positivity_projection(ada, floor)[0]
        ar = apply_positivity_projection(ar, floor)[0]
        dm, p, lag = dm_test(y, ada, ar, horizon=h)
        rows.append({"horizon": h, "order": str(order), "mse": metrics["MSE"],
                     "qlike": metrics["QLIKE"], "dm_vs_ada": dm,
                     "p_raw_vs_ada": p, "hac_lag": lag})
    out = RESULTS / "rolling_arima.csv"
    pd.DataFrame(rows).to_csv(out, index=False)
    print(f"[saved] {out}")
    return out


