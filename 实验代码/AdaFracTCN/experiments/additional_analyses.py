def _closest_tcn_width(layers: int, kernel: int, target=365015) -> int:
    best = None
    for w in range(32, 193):
        p = analytic_param_count("TCN", hidden_dim=w, num_layers=layers, kernel_size=kernel)
        cand = (abs(p - target), w, p)
        if best is None or cand < best:
            best = cand
    return int(best[1])


def _transformer_count(width: int, cfg: dict) -> int:
    m = TransformerModel(hidden_dim=width, n_heads=cfg["n_heads"],
                         num_layers=cfg["num_layers"], ffn_mult=cfg["ffn_mult"],
                         dropout=cfg.get("dropout", 0.2))
    return m.count_parameters()


def _closest_transformer_width(cfg: dict, target=365015) -> int:
    best = None
    heads = cfg["n_heads"]
    for w in range(max(32, heads), 257):
        if w % heads:
            continue
        p = _transformer_count(w, cfg)
        cand = (abs(p - target), w, p)
        if best is None or cand < best:
            best = cand
    return int(best[1])


def _tuning_grid() -> Dict[str, List[dict]]:
    tcn_shapes = [(3, 7), (4, 3), (4, 5), (5, 3)]
    tcn = [{"num_layers": L, "kernel_size": K,
            "hidden_dim": _closest_tcn_width(L, K)} for L, K in tcn_shapes]
    tf_base = [
        {"n_heads": 2, "num_layers": 1, "ffn_mult": 2.0, "dropout": 0.2},
        {"n_heads": 4, "num_layers": 1, "ffn_mult": 2.0, "dropout": 0.1},
        {"n_heads": 4, "num_layers": 1, "ffn_mult": 3.0, "dropout": 0.2},
        {"n_heads": 4, "num_layers": 2, "ffn_mult": 2.0, "dropout": 0.2},
    ]
    tf = []
    for c in tf_base:
        c = dict(c); c["hidden_dim"] = _closest_transformer_width(c); tf.append(c)
    inf = [
        {"hidden_dim": 116, "n_heads": 4, "topk": 2, "dropout": 0.2},
        {"hidden_dim": 116, "n_heads": 4, "topk": 4, "dropout": 0.1},
        {"hidden_dim": 116, "n_heads": 4, "topk": 8, "dropout": 0.2},
        {"hidden_dim": 116, "n_heads": 4, "topk": 16, "dropout": 0.2},
    ]
    frac = [
        {"hidden_dim": 300, "alpha": 0.3, "truncation": 32},
        {"hidden_dim": 300, "alpha": 0.5, "truncation": 64},
        {"hidden_dim": 300, "alpha": 0.7, "truncation": 64},
        {"hidden_dim": 300, "alpha": 0.5, "truncation": 128},
    ]
    return {"TCN": tcn, "Transformer": tf, "Informer": inf, "Frac-LSTM": frac}


def _build_tuned(model: str, h: int, cfg: dict, mode="standard"):
    if model == "TCN":
        return get_adafractcn("TCN", horizon=h, mode=mode, **cfg)
    if model == "Transformer":
        return TransformerModel(horizon=h, mode=mode, **cfg)
    if model == "Informer":
        return InformerModel(horizon=h, mode=mode, **cfg)
    if model == "Frac-LSTM":
        return FracLSTMModel(horizon=h, mode=mode, **cfg)
    raise ValueError(model)


def baseline_tuning() -> Tuple[Path, Path]:
    device = "cuda" if torch.cuda.is_available() else "cpu"
    grid = _tuning_grid()
    rows, selected = [], {}
    for h in HORIZONS:
        Xtr, ytr, Xv, yv, Xt, yt, scaling, floor = _load_h(h)
        tr = _loader(Xtr, ytr, 256, True); va = _loader(Xv, yv, 256, False)
        selected[str(h)] = {}
        for model in TUNED_FAMILIES:
            candidates = grid[model]
            scores = []
            for ci, cfg in enumerate(candidates):
                mse_seed = []
                for seed in TUNE_SEEDS:
                    set_seed(seed)
                    m = _build_tuned(model, h, cfg)
                    m.fit(tr, va, device=device)
                    pv = m.predict(va, device=device)
                    met = compute_metrics(yv, pv, scaling=scaling, floor=floor)
                    mse_seed.append(float(met["MSE"]))
                mean = float(np.mean(mse_seed))
                sd = float(np.std(mse_seed, ddof=1))
                params = int(_build_tuned(model, h, cfg, mode="quick").count_parameters())
                rows.append({"horizon": h, "model": model, "candidate": ci,
                             "config": json.dumps(cfg, sort_keys=True),
                             "validation_mse_mean": mean, "validation_mse_sd": sd,
                             "selection_seeds": len(TUNE_SEEDS), "params": params})
                scores.append((mean, ci, cfg))
            _, best_i, best_cfg = min(scores, key=lambda x: x[0])
            selected[str(h)][model] = {"candidate": int(best_i), **best_cfg}
    out_csv = RESULTS / "baseline_tuning.csv"
    out_json = RESULTS / "baseline_tuning_selected.json"
    pd.DataFrame(rows).to_csv(out_csv, index=False)
    out_json.write_text(json.dumps(selected, indent=2), encoding="utf-8")
    print(f"[saved] {out_csv}\n[saved] {out_json}")
    return out_csv, out_json


def tuned_test() -> Path:
    selected = json.loads(_need(RESULTS / "baseline_tuning_selected.json").read_text())
    device = "cuda" if torch.cuda.is_available() else "cpu"
    out_dir = RESULTS / "tuned_raw"
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for h in HORIZONS:
        Xtr, ytr, Xv, yv, Xt, yt, scaling, floor = _load_h(h)
        tr = _loader(Xtr, ytr, 256, True); va = _loader(Xv, yv, 256, False); te = _loader(Xt, yt, 256, False)
        for model in TUNED_FAMILIES:
            cfg = dict(selected[str(h)][model]); cfg.pop("candidate", None)
            preds, mets = [], []
            for seed in SEEDS:
                set_seed(seed)
                m = _build_tuned(model, h, cfg)
                m.fit(tr, va, device=device)
                p = m.predict(te, device=device)
                preds.append(p); mets.append(compute_metrics(yt, p, scaling=scaling, floor=floor))
            pred = np.stack(preds, axis=0)
            ens = compute_metrics(yt, pred.mean(axis=0), scaling=scaling, floor=floor)
            dates = np.load(DATA / f"h{h}" / "origin_dates_test.npy", allow_pickle=False)
            np.savez_compressed(out_dir / f"h{h}__{_slug(model)}.npz",
                                predictions_std=pred.astype(np.float32), y_test_std=yt.astype(np.float32),
                                origin_dates=dates, target_mean=float(scaling[0]), target_std=float(scaling[1]),
                                positivity_floor=float(floor), seeds=np.asarray(SEEDS, np.int64),
                                config=json.dumps(cfg, sort_keys=True))
            rows.append({"model": model, "horizon": h,
                         "mse_mean": float(np.mean([x["MSE"] for x in mets])),
                         "mse_sd": float(np.std([x["MSE"] for x in mets], ddof=1)),
                         "ensemble_mse": float(ens["MSE"]),
                         "qlike_mean": float(np.mean([x["QLIKE"] for x in mets])),
                         "ensemble_qlike": float(ens["QLIKE"]),
                         "config": json.dumps(cfg, sort_keys=True)})
    out = RESULTS / "tuned_test_summary.csv"
    pd.DataFrame(rows).to_csv(out, index=False)
    print(f"[saved] {out}")
    return out


