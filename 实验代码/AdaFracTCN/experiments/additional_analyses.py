# 6) Residual-memory uncertainty on non-overlapping h=10 origins
# -----------------------------------------------------------------------------
def _circular_block_indices(n: int, block: int, rng) -> np.ndarray:
    out=[]; block=max(1,min(block,n))
    while len(out)<n:
        s=int(rng.integers(0,n)); out.extend(((s+np.arange(block))%n).tolist())
    return np.asarray(out[:n],int)




def residual_uncertainty(bootstrap_reps=1000, block_len=5) -> Path:
    """Recompute residual Hurst point estimates and non-overlap uncertainty.

    The same saved ensemble forecast paths feed both the main residual-Hurst
    table and the moving-block-bootstrap follow-up table.  This intentionally
    prevents point estimates in the two manuscript locations from drifting.
    """
    models = ["ARIMA", "LSTM", "GRU", "TCN", "Transformer", "Informer",
              "Frac-LSTM", "AdaFracTCN"]
    h = 10
    rng = np.random.default_rng(20260918)
    full_series, no_series = {}, {}

    z0 = _load_raw("AdaFracTCN", h)
    scaling = (float(z0["target_mean"]), float(z0["target_std"]))
    floor = float(z0["positivity_floor"])
    y = inverse_target(np.asarray(z0["y_test_std"], float), scaling)
    target_abs = np.abs(y)
    full_series["Target"] = target_abs
    no_series["Target"] = target_abs[::h]

    for model in models:
        z = _load_raw(model, h)
        p = inverse_target(np.asarray(z["predictions_std"], float).mean(axis=0), scaling)
        p = apply_positivity_projection(p, floor)[0]
        abs_res = np.abs(y - p)
        full_series[model] = abs_res
        no_series[model] = abs_res[::h]

    rows = []
    for name in ["Target"] + models:
        x_full = full_series[name]
        x = no_series[name]
        point_full_dfa, point_full_rs = compute_hurst(x_full)
        point_dfa, point_rs = compute_hurst(x)
        bd, br = [], []
        for _ in range(int(bootstrap_reps)):
            xb = x[_circular_block_indices(len(x), block_len, rng)]
            try:
                a, b = compute_hurst(xb)
                bd.append(a); br.append(b)
            except Exception:
                continue
        if len(bd) < max(100, bootstrap_reps // 3):
            raise RuntimeError(f"Too few valid Hurst bootstrap replicates for {name}: {len(bd)}")
        rows.append({
            "series_model": name,
            "n_full": len(x_full), "n": len(x),
            "mfdfa_full": point_full_dfa, "rs_full": point_full_rs,
            "mfdfa": point_dfa,
            "mfdfa_low": float(np.quantile(bd, .025)),
            "mfdfa_high": float(np.quantile(bd, .975)),
            "rs": point_rs,
            "rs_low": float(np.quantile(br, .025)),
            "rs_high": float(np.quantile(br, .975)),
            "bootstrap_reps": len(bd), "block_len": block_len,
        })

    df = pd.DataFrame(rows)
    out = RESULTS / "residual_hurst_uncertainty.csv"
    df.to_csv(out, index=False)

    print(f"[saved] {out}")
    return out


