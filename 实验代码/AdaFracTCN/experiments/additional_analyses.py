# 4) Fitted effective-kernel diagnostic
# -----------------------------------------------------------------------------
def effective_kernels(sample_per_regime=64) -> Tuple[Path, Path]:
    """Reconstruct fitted effective kernels from saved checkpoints and alpha traces.

    The exported CSV contains all four blocks, both long/short branches, and both
    serial fractional-convolution stages.  The manuscript figure deliberately
    shows only stage 1 in Blocks 1 and 4 (early/late) to remain legible; the full
    numerical diagnostic remains in the CSVs.
    """
    h = 10
    z = _load_raw("AdaFracTCN", h)
    alpha = np.asarray(z["alpha_trace"], float)  # seed,date,block,2
    if alpha.ndim != 4 or alpha.shape[0] != len(SEEDS) or alpha.shape[-1] != 2:
        raise ValueError(f"Unexpected alpha_trace shape: {alpha.shape}")

    Xtr = np.load(_need(DATA / f"h{h}" / "X_train.npy"), allow_pickle=False)
    Xte = np.load(_need(DATA / f"h{h}" / "X_test.npy"), allow_pickle=False)
    labels, _, _ = split_regime_from_windows(
        Xtr, Xte, load_input_scaling(str(DATA)), window=20)
    idx_by_regime = {}
    for reg in ["calm", "turbulent"]:
        idx = np.where(labels == reg)[0]
        if len(idx) == 0:
            raise RuntimeError(f"No {reg} origins available for fitted-kernel diagnostic")
        if len(idx) > sample_per_regime:
            # Deterministic equal-spacing selection avoids adding another random seed.
            pos = np.linspace(0, len(idx) - 1, sample_per_regime).round().astype(int)
            idx = idx[pos]
        idx_by_regime[reg] = idx

    # key -> list of (n_origin, n_lag) normalized curves, one list item per seed.
    curves_by_key = {}
    cancellation = []
    conv_specs = [
        ("long", 1, "conv_long1", 0),
        ("long", 2, "conv_long2", 0),
        ("short", 1, "conv_short1", 1),
        ("short", 2, "conv_short2", 1),
    ]

    for si, seed in enumerate(SEEDS):
        ck = _need(CHECKPOINTS / f"adafractcn_h{h}_seed{seed}.pt")
        payload = torch.load(ck, map_location="cpu")
        model = get_adafractcn("AdaFracTCN", horizon=h, mode="standard")
        model.load_state_dict(payload["state_dict"])
        model.eval()

        if len(model.net) != alpha.shape[2]:
            raise ValueError(
                f"Checkpoint block count {len(model.net)} does not match alpha trace {alpha.shape[2]}")

        for bi, block in enumerate(model.net):
            for branch, stage, attr, alpha_col in conv_specs:
                conv = getattr(block, attr)
                w = conv.w.detach().cpu().numpy()
                ratio = np.abs(w.sum(axis=-1)) / (np.abs(w).sum(axis=-1) + 1e-12)
                cancellation.append({
                    "seed": seed,
                    "block": bi + 1,
                    "branch": branch,
                    "stage": stage,
                    "rho_w_median_channel_pair": float(np.median(ratio)),
                    "rho_w_q25_channel_pair": float(np.quantile(ratio, 0.25)),
                    "rho_w_q75_channel_pair": float(np.quantile(ratio, 0.75)),
                })

                for reg, idx in idx_by_regime.items():
                    a = torch.as_tensor(alpha[si, idx, bi, alpha_col], dtype=conv.w.dtype)
                    seed_curves = []
                    for j in range(0, len(idx), 16):
                        ker = conv.materialize_effective_kernel(a[j:j + 16]).detach().cpu().numpy()
                        # Mean absolute fitted coefficient across input/output channel pairs.
                        c = np.mean(np.abs(ker), axis=(1, 2))
                        c = c / np.maximum(c.sum(axis=1, keepdims=True), 1e-12)
                        seed_curves.append(c)
                    seed_curves = np.concatenate(seed_curves, axis=0)
                    curves_by_key.setdefault((bi + 1, branch, stage, reg), []).append(seed_curves)

    # Aggregate equally sampled origin-seed curves; keep all blocks/stages in CSV.
    rows = []
    tail_rows = []
    for (block, branch, stage, reg), parts in sorted(curves_by_key.items()):
        mat = np.concatenate(parts, axis=0)
        med = np.median(mat, axis=0)
        q25 = np.quantile(mat, 0.25, axis=0)
        q75 = np.quantile(mat, 0.75, axis=0)
        for lag in range(mat.shape[1]):
            rows.append({
                "block": block, "branch": branch, "stage": stage,
                "regime": reg, "lag": lag,
                "median": float(med[lag]), "q25": float(q25[lag]),
                "q75": float(q75[lag]), "n_curves": int(mat.shape[0]),
            })
        tail_start = min(32, mat.shape[1] - 1)
        tail_mass = mat[:, tail_start:].sum(axis=1)
        tail_rows.append({
            "block": block, "branch": branch, "stage": stage, "regime": reg,
            "tail_start_lag": tail_start,
            "tail_mass_median": float(np.median(tail_mass)),
            "tail_mass_q25": float(np.quantile(tail_mass, 0.25)),
            "tail_mass_q75": float(np.quantile(tail_mass, 0.75)),
            "n_curves": int(mat.shape[0]),
        })

    df = pd.DataFrame(rows)
    out_csv = RESULTS / "effective_kernels.csv"
    df.to_csv(out_csv, index=False)

    cancel_df = pd.DataFrame(cancellation)
    cancel_path = RESULTS / "effective_kernel_cancellation.csv"
    cancel_df.to_csv(cancel_path, index=False)
    cancel_summary = (cancel_df.groupby(["block", "branch", "stage"], as_index=False)
                      .agg(rho_w_median=("rho_w_median_channel_pair", "median"),
                           rho_w_q25=("rho_w_median_channel_pair", lambda x: np.quantile(x, 0.25)),
                           rho_w_q75=("rho_w_median_channel_pair", lambda x: np.quantile(x, 0.75)),
                           n_seeds=("seed", "nunique")))
    cancel_summary_path = RESULTS / "effective_kernel_cancellation_summary.csv"
    cancel_summary.to_csv(cancel_summary_path, index=False)
    tail_df = pd.DataFrame(tail_rows)
    tail_df.to_csv(RESULTS / "effective_kernel_tail_summary.csv", index=False)

    # Manuscript figure: stage 1 in early and late blocks, with IQR ribbons.
    import matplotlib.pyplot as plt
    fig_style.apply(serif=True)
    panels = [(1, "long"), (1, "short"), (4, "long"), (4, "short")]
    fig, axes = plt.subplots(2, 2, figsize=(7.2, 5.2), sharex=True, sharey=True)
    for ax, (block, branch) in zip(axes.flat, panels):
        for reg, ls in [("calm", "-"), ("turbulent", "--")]:
            d = df[(df.block == block) & (df.branch == branch) &
                   (df.stage == 1) & (df.regime == reg)].sort_values("lag")
            if d.empty:
                raise RuntimeError(f"No fitted-kernel rows for block={block}, branch={branch}, {reg}")
            x = d["lag"].to_numpy(float)
            y = d["median"].to_numpy(float)
            lo = d["q25"].to_numpy(float)
            hi = d["q75"].to_numpy(float)
            line = ax.plot(x, y, linestyle=ls, linewidth=1.6, label=reg.capitalize())[0]
            ax.fill_between(x, lo, hi, alpha=0.16, color=line.get_color(), linewidth=0)
        ax.set_yscale("log")
        ax.grid(True, alpha=0.18)
        ax.set_title(f"Block {block}, {branch} branch")
        ax.set_xlabel("Lag $k$")
    axes[0, 0].set_ylabel("Normalized fitted $|A_k|$")
    axes[1, 0].set_ylabel("Normalized fitted $|A_k|$")
    axes[0, 1].legend(frameon=False)
    fig.tight_layout()

    FIGURES.mkdir(parents=True, exist_ok=True)
    out_fig = FIGURES / "fitted_effective_kernels.pdf"
    fig.savefig(out_fig, format="pdf", bbox_inches="tight")
    plt.close(fig)

    print(f"[saved] {out_csv}\n[saved] {cancel_path}\n[saved] {cancel_summary_path}\n[saved] {out_fig}")
    return out_csv, out_fig


