# 5) Time-series-aware ablation inference from date-wise losses
# -----------------------------------------------------------------------------
def _hac_mean_ci(d: np.ndarray, lag: int, alpha=0.05) -> dict:
    d = np.asarray(d, float); n = len(d); mu = float(d.mean())
    x = d - mu
    gamma0 = float(np.dot(x, x) / n)
    s = gamma0
    lag = min(max(1, int(lag)), n-1)
    for k in range(1, lag+1):
        w = 1.0 - k/(lag+1.0)
        gam = float(np.dot(x[k:], x[:-k]) / n)
        s += 2*w*gam
    se = math.sqrt(max(s, 0.0)/n)
    z = mu/se if se > 0 else np.nan
    p = 2*(1-sp_stats.norm.cdf(abs(z))) if np.isfinite(z) else np.nan
    q = sp_stats.norm.ppf(1-alpha/2)
    return {"mean_delta": mu, "hac_se": se, "ci_low": mu-q*se,
            "ci_high": mu+q*se, "z": z, "p": p, "lag": lag, "n": n}


def ablation_timeseries() -> Path:
    raw_dir = _need(RESULTS / "ablation_raw_predictions")
    idx = pd.read_csv(_need(raw_dir / "index.csv"))
    h = int(idx["horizon"].iloc[0])
    tcn_file = idx[idx.variant == "TCN"].iloc[0]["file"]
    tcn = np.load(raw_dir / tcn_file, allow_pickle=False)
    scaling = (float(tcn["target_mean"]), float(tcn["target_std"])); floor = float(tcn["positivity_floor"])
    y = inverse_target(np.asarray(tcn["y_test_std"], float), scaling)
    pt = inverse_target(np.asarray(tcn["predictions_std"], float).mean(axis=0), scaling)
    pt = apply_positivity_projection(pt, floor)[0]
    loss_t = (y-pt)**2
    rows=[]
    plugin = int(np.floor(4*(len(y)/100)**(2/9)))
    lag = max(h-1, plugin, 1)
    for _, r in idx.iterrows():
        var = str(r["variant"])
        if var == "TCN": continue
        z = np.load(raw_dir / str(r["file"]), allow_pickle=False)
        p = inverse_target(np.asarray(z["predictions_std"], float).mean(axis=0), scaling)
        p = apply_positivity_projection(p, floor)[0]
        # positive delta means variant improves over TCN
        d = loss_t - (y-p)**2
        rec={"variant":var}; rec.update(_hac_mean_ci(d,lag)); rows.append(rec)
    out=RESULTS/"ablation_hac.csv"
    pd.DataFrame(rows).to_csv(out,index=False)
    print(f"[saved] {out}")
    return out


