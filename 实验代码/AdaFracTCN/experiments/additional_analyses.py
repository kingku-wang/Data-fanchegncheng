TABLE3_TRAINABLE_MODELS = [
    "LSTM", "GRU", "TCN", "Transformer", "Informer", "Frac-LSTM", "AdaFracTCN"
]






def ensemble_summary() -> Path:
    rows = []
    index = pd.read_csv(_need(RAW / "index.csv"))
    for _, r in index.iterrows():
        model, h = str(r["model"]), int(r["horizon"])
        z = _load_raw(model, h)
        pred = np.asarray(z["predictions_std"], float)
        if model in TABLE3_TRAINABLE_MODELS and pred.shape[0] != len(SEEDS):
            raise RuntimeError(
                f"{model}, h={h}: expected {len(SEEDS)} saved seed forecasts, found {pred.shape[0]}")
        per_seed = [_score_saved(z, p) for p in pred]
        ens = _score_saved(z, pred.mean(axis=0))
        rows.append({
            "model": model, "horizon": h,
            "mse_mean": float(np.mean([m["MSE"] for m in per_seed])),
            "mse_sd": float(np.std([m["MSE"] for m in per_seed], ddof=1)) if len(per_seed) > 1 else 0.0,
            "qlike_mean": float(np.mean([m["QLIKE"] for m in per_seed])),
            "qlike_sd": float(np.std([m["QLIKE"] for m in per_seed], ddof=1)) if len(per_seed) > 1 else 0.0,
            "ensemble_mse": float(ens["MSE"]),
            "ensemble_qlike": float(ens["QLIKE"]),
            "n_seeds": int(pred.shape[0]),
        })
    df = pd.DataFrame(rows).sort_values(["horizon", "model"])
    out = RESULTS / "seed_ensemble_summary.csv"
    df.to_csv(out, index=False)
    print(f"[saved] {out}")
    return out


