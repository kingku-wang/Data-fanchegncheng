def _slug(name: str) -> str:
    return (name.lower().replace("(1,1)", "11").replace(".", "")
            .replace(" ", "_").replace("-", "_").replace("/", "_"))


def _need(path: Path) -> Path:
    if not path.exists():
        raise FileNotFoundError(f"Required real-run artifact missing: {path}")
    return path


def _load_h(h: int):
    d = DATA / f"h{h}"
    names = ["X_train", "y_train", "X_val", "y_val", "X_test", "y_test"]
    arr = [np.load(_need(d / f"{n}.npy"), allow_pickle=False) for n in names]
    return (*arr, load_target_scaling(str(DATA), h), load_positivity_floor(str(DATA), h))


def _loader(X, y, batch=256, shuffle=False):
    from torch.utils.data import TensorDataset, DataLoader
    ds = TensorDataset(torch.as_tensor(X, dtype=torch.float32),
                       torch.as_tensor(y, dtype=torch.float32))
    return DataLoader(ds, batch_size=batch, shuffle=shuffle)


def _load_raw(model: str, h: int) -> dict:
    p = _need(RAW / f"h{h}__{_slug(model)}.npz")
    z = np.load(p, allow_pickle=False)
    return {k: z[k] for k in z.files}


def _score_saved(z: dict, predictions_std: np.ndarray) -> dict:
    scaling = (float(z["target_mean"]), float(z["target_std"]))
    floor = float(z["positivity_floor"])
    return compute_metrics(np.asarray(z["y_test_std"], float),
                           np.asarray(predictions_std, float),
                           scaling=scaling, floor=floor)


